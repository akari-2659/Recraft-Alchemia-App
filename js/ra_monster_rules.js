function keysFromText(text=''){
  const source=String(text||'');
  return Object.keys(definitions).filter(key=>patterns[key]?patterns[key].test(source):source.includes(key));
}
function notesFromText(text=''){
  return [...new Set(keysFromText(text).flatMap(key=>definitions[key]))];
}
function validateText(text=''){
  const source=String(text||'');
  const expanded=[source,...notesFromText(source)].join('。');
  // Check explicit damage clauses, not bonus dice or healing expressions.
  const ambiguous=[...expanded.matchAll(/(?:\d+D\d+(?:[+]\d+(?:D\d+)?)?)(?:の)?(?:[物火水風雷光闇無]属性)?[・ ]*ダメージ/g)].map(m=>m[0]);
  return [...new Set(ambiguous)].map(value=>'ダメージ種別未記載：'+value+'（通常ダメージ／防御無視ダメージを明記）');
}
function fieldCommands(text=''){
  return keysFromText(text).filter(key=>fields[key]).flatMap(key=>{
    const f=fields[key];
    return [`2D6+${f.hit}>=回避値 【${key}・終了時判定／妨害対象外】`,`${f.power} 【${key}・${f.element}属性${f.damageKind}ダメージ】`];
  });
}
